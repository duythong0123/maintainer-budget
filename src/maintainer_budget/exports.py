from __future__ import annotations

from .models import CandidateRule, ReviewComment


def _one_line(text: str, limit: int = 150) -> str:
    value = " ".join(text.strip().split())
    if len(value) <= limit:
        return value
    return value[: limit - 3].rstrip() + "..."


def render_share_card(
    repo: str,
    all_comments: list[ReviewComment],
    actionable: list[ReviewComment],
    candidates: list[CandidateRule],
    *,
    top: int = 3,
) -> str:
    """Render a compact, copy-pasteable Markdown summary.

    The share card deliberately reports only observed counts and candidate
    evidence. It does not claim that a candidate is an accepted repository rule.
    """
    lines = [
        f"## Maintainer Budget · `{repo}`",
        "",
        f"**{len(all_comments)}** review comments · "
        f"**{len(actionable)}** actionable human comments · "
        f"**{len(candidates)}** recurring candidates",
        "",
    ]

    if candidates:
        lines.append("Top recurring candidates:")
        lines.append("")
        for candidate in candidates[: max(1, top)]:
            lines.append(
                f"- **{candidate.rule_id}** · {candidate.unique_prs} PRs · "
                f"{candidate.unique_reviewers} reviewers — {_one_line(candidate.representative, 120)}"
            )
        lines.append("")
    else:
        lines += ["No recurring candidate passed the current threshold.", ""]

    lines += [
        "_Evidence-backed candidates only. Human approval is required before treating any candidate as repository policy._",
        "",
        "Generated by [Maintainer Budget](https://github.com/duythong0123/maintainer-budget).",
    ]
    return "\n".join(lines)


def render_codex_bundle(repo: str, candidates: list[CandidateRule], *, top: int = 12) -> str:
    """Render an evidence bundle that a maintainer can hand to Codex.

    This export is intentionally model-agnostic and performs no API call. The
    core package therefore stays dependency-free while providing a strict,
    provenance-preserving semantic-review workflow for Codex users.
    """
    selected = candidates[: max(1, top)]
    lines = [
        "# Maintainer Budget → Codex evidence bundle",
        "",
        f"Repository: `{repo}`",
        "",
        "## Task",
        "",
        "Review the candidate clusters below and propose concise repository-specific rules only when the supplied human-review evidence supports them.",
        "",
        "## Hard constraints",
        "",
        "1. Do not invent a rule that is not supported by the supplied evidence.",
        "2. Do not turn generic programming advice into repository policy.",
        "3. Preserve candidate IDs and evidence URLs in every proposal.",
        "4. Merge candidates only when their evidence expresses the same repository convention.",
        "5. Mark ambiguous, conflicting, or likely stale candidates as `REVIEW` instead of guessing.",
        "6. Do not edit `AGENTS.md` or any policy file automatically.",
        "",
        "## Requested output",
        "",
        "For each candidate, return:",
        "",
        "```text",
        "ID: MB-xxx",
        "VERDICT: PROPOSE | MERGE | REVIEW | REJECT",
        "RULE: <one concise rule, or empty for REVIEW/REJECT>",
        "SCOPE: <path/glob if evidence supports one, otherwise repository-wide/unknown>",
        "WHY: <brief evidence-based reason>",
        "EVIDENCE: <original URLs>",
        "```",
        "",
        "## Candidates",
        "",
    ]

    if not selected:
        lines.append("No recurring candidates passed the current threshold.")
        return "\n".join(lines)

    for candidate in selected:
        lines += [
            f"### {candidate.rule_id}",
            "",
            f"Representative feedback: {_one_line(candidate.representative, 300)}",
            "",
            f"Observed across {candidate.unique_prs} PRs and {candidate.unique_reviewers} reviewers.",
            "",
            "Evidence:",
            "",
        ]
        for evidence in candidate.comments[:12]:
            path = f" · `{evidence.path}`" if evidence.path else ""
            lines.append(
                f"- PR #{evidence.pr_number} · @{evidence.author}{path} · "
                f"{evidence.url}\n  - {_one_line(evidence.body, 260)}"
            )
        if len(candidate.comments) > 12:
            lines.append(f"- ... {len(candidate.comments) - 12} additional evidence comments omitted")
        lines.append("")

    lines += [
        "## Maintainer decision",
        "",
        "Treat Codex output as a proposal. The maintainer remains responsible for ACCEPT / EDIT / REJECT / STALE decisions.",
    ]
    return "\n".join(lines)
